def arm(a, r0=10, r1=72):
    return l(*on(100, 100, r0, a), *on(100, 100, r1, a))


def twig(a, rr, size=16):
    base = on(100, 100, rr, a)
    return [l(*base, *on(base[0], base[1], size, a - 45)), l(*base, *on(base[0], base[1], size, a + 45))]


