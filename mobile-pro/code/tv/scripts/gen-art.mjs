// Generates src/art/registry.ts from the .webp files in src/art/images, so
// every illustration gets a static require() (needed by Metro) and a typed
// name. The images are a copy of packages/ui/art (MIT, Microsoft Fluent
// Emoji 3D); tv/ is outside the npm workspace and cannot import @pro/ui.
// Run with `npm run gen:art` after adding art.
import { readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'src/art/images');
const names = readdirSync(dir)
  .filter((f) => f.endsWith('.webp'))
  .map((f) => f.replace(/\.webp$/, ''))
  .sort();

const lines = [
  '// Generated by scripts/gen-art.mjs from src/art/images. Do not edit by hand;',
  '// run `npm run gen:art` instead.',
  "import type { ImageSourcePropType } from 'react-native';",
  '',
  'export const ART_NAMES = [',
  ...names.map((n) => `  '${n}',`),
  '] as const;',
  '',
  'export type ArtName = (typeof ART_NAMES)[number];',
  '',
  'export const artSources: Record<ArtName, ImageSourcePropType> = {',
  ...names.map((n) => `  '${n}': require('./images/${n}.webp'),`),
  '};',
  '',
];
writeFileSync(join(root, 'src/art/registry.ts'), lines.join('\n'));
console.log(`Wrote ${names.length} art names to src/art/registry.ts`);
