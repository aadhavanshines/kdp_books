// Generates src/art/registry.ts from art/index.json so that every
// illustration gets a static require() (needed by Metro) and a typed name.
// Run with `npm run gen:art -w packages/ui` after adding art.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const names = JSON.parse(readFileSync(join(root, 'art/index.json'), 'utf8'));

if (!Array.isArray(names) || names.some((n) => typeof n !== 'string')) {
  throw new Error('art/index.json must be an array of strings');
}
const sorted = [...new Set(names)].sort();
for (const name of sorted) {
  if (!existsSync(join(root, 'art', `${name}.webp`))) {
    throw new Error(`art/index.json lists "${name}" but art/${name}.webp is missing`);
  }
}

const lines = [
  '// Generated by scripts/gen-art.mjs from art/index.json. Do not edit by hand;',
  '// run `npm run gen:art -w packages/ui` instead.',
  "import type { ImageSourcePropType } from 'react-native';",
  '',
  'export const ART_NAMES = [',
  ...sorted.map((n) => `  '${n}',`),
  '] as const;',
  '',
  'export type ArtName = (typeof ART_NAMES)[number];',
  '',
  'export const artSources: Record<ArtName, ImageSourcePropType> = {',
  ...sorted.map((n) => `  '${n}': require('../../art/${n}.webp'),`),
  '};',
  '',
];
writeFileSync(join(root, 'src/art/registry.ts'), lines.join('\n'));

// The API package gets the same names as a plain type (no images), so the
// server's seed data and the API types are checked against real art.
const apiLines = [
  '// Generated by packages/ui/scripts/gen-art.mjs from packages/ui/art/index.json.',
  '// Do not edit by hand; run `npm run gen:art -w packages/ui` instead.',
  '',
  'export const ART_NAMES = [',
  ...sorted.map((n) => `  '${n}',`),
  '] as const;',
  '',
  'export type ArtName = (typeof ART_NAMES)[number];',
  '',
];
writeFileSync(join(root, '../api/src/art.ts'), apiLines.join('\n'));
console.info(`Wrote ${sorted.length} art entries to src/art/registry.ts and ../api/src/art.ts`);
